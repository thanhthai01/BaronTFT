CONDITION_SPLIT_RE = re.compile(r"(?<=[a-z0-9])(?=(?:Have|Be |Not |At least|First \d|Board value))")


def load_charm_index() -> tuple[dict, dict]:
    """apiName -> charm, và desc_en -> [charm] để dò biến thể nâng cấp khi thiếu _Upgrade."""
    codex = json.loads(CODEX_VI_JSON.read_text(encoding="utf-8"))
    by_api = {c["apiName"]: c for c in codex["charms"]}
    by_desc_en: dict[str, list] = {}
    for c in codex["charms"]:
        by_desc_en.setdefault((c.get("desc_en") or "").strip(), []).append(c)
    trait_vi = {
        t["name_en"]: t["name"]
        for t in codex["traits"]
        if t.get("name_en") and t.get("name") and t["name_en"] != t["name"]
    }
    return by_api, {"desc": by_desc_en, "trait": trait_vi}


def make_trait_localizer(trait_vi: dict):
    """Thay tên tộc/hệ tiếng Anh còn sót trong câu điều kiện bằng tên tiếng Việt.
    Ghép tên dài trước để "Apex Predator" không bị "Apex" nuốt mất."""
    if not trait_vi:
        return lambda s: s
    pattern = re.compile(r"\b(" + "|".join(re.escape(k) for k in sorted(trait_vi, key=len, reverse=True)) + r")\b")
    return lambda s: pattern.sub(lambda m: trait_vi[m.group(1)], s)


def translate_condition(fragment: str, localize_trait) -> str:
    for pattern, builder in CONDITION_PATTERNS:
        match = re.match(pattern, fragment)
        if match:
            return localize_trait(builder(match))
    return fragment


def build_conditions(conditions_en: str | None, localize_trait) -> list[str]:
    if not conditions_en:
        return []
    text = conditions_en.removeprefix("Requires:")
    fragments = [f.strip() for f in CONDITION_SPLIT_RE.split(text) if f.strip()]
    return [translate_condition(f, localize_trait) for f in fragments]


def build_appears(bounds: dict) -> str:
    """Dựng lại từ round_bounds thay vì dùng chuỗi "Appears:" cào từ DOM — chuỗi đó nằm
    ở phía tiếng Việt nên đã bị lệch hàng (có wisp hiện 3-1 đến 4-1 trong khi
    round_bounds thật là 2-1 đến 2-7)."""
    start, end = bounds.get("start"), bounds.get("end")
    if not start:
        return ""
    if end and end != start:
        return f"Xuất hiện: {start} đến {end}"
    return f"Xuất hiện: {start}"


def find_upgrade_charm(api: str, upgrade_desc_en: str | None, by_api: dict, by_desc_en: dict):
    """Charm bản nâng cấp Hoa Linh. 118/135 dùng hậu tố _Upgrade; số còn lại đặt apiName
    khác hẳn nên dò tiếp bằng desc_en (khớp tuyệt đối, ưu tiên charm cùng gốc apiName).

    Điều kiện vào cửa là wisp phải có `blossom_upgrade_description_en` — bảng charm có
    biến thể `_Upgrade` cho cả những linh hỏa KHÔNG hiện nút nâng cấp Hoa Linh trên web,
    nên nếu dò thẳng theo apiName sẽ gán nhầm bản nâng cấp cho 39 linh hỏa không có."""
    if not upgrade_desc_en:
        return None
    direct = by_api.get(f"{api}_Upgrade")
    if direct:
        return direct
    candidates = by_desc_en.get(upgrade_desc_en.strip(), [])
    if not candidates:
        return None
    same_root = [c for c in candidates if c["apiName"].startswith(api)]
    return (same_root or candidates)[0]


def remap_icon(category_icon: dict) -> str:
    fname = Path(category_icon["local_path"]).name
    return f"/set18/assets/wisp_categories/{fname}"


def build_wisp(w: dict, by_api: dict, by_desc_en: dict, localize_trait) -> dict:
    api = w["matched_charm"]["apiName"]
    charm = by_api[api]
    bounds = (w.get("matched_charm") or {}).get("round_bounds") or {}
    upgrade = find_upgrade_charm(api, w.get("blossom_upgrade_description_en"), by_api, by_desc_en)
    return {
        "name": w["name_en"],
        "nameVi": charm["name"],
        "category": w["category"],
        "categoryVi": CATEGORY_VI.get(w["category"], w["category"]),
        "categoryIcon": remap_icon(w["category_icon"]),
        "tier": w["tier"],
        "cost": w["cost"],
        "description": w["description_en"] or "",
        "descriptionVi": charm["desc"] or "",
        "blossomUpgradeCost": w["blossom_upgrade_cost"],
        "blossomUpgradeDescriptionVi": (upgrade["desc"] or None) if upgrade else None,
        "appearsVi": build_appears(bounds),
        "appearsStart": bounds.get("start"),
        "appearsEnd": bounds.get("end"),
        "conditionsVi": build_conditions(w["conditions_en"], localize_trait),
    }


def main() -> None:
    data = json.loads(WISPS_JSON.read_text(encoding="utf-8"))
    wisps = data["wisps"]
    by_api, extra = load_charm_index()
    localize_trait = make_trait_localizer(extra["trait"])

    icon_dir = WEBSITE / "public" / "set18" / "assets" / "wisp_categories"
    available = {p.name for p in icon_dir.iterdir()}
    missing_icons = sorted({Path(w["category_icon"]["local_path"]).name for w in wisps} - available)
    if missing_icons:
        raise SystemExit(f"Thieu icon phan loai: {missing_icons}")

    # dừng sớm nếu bảng charm không phủ hết — không có apiName thì không dựng lại được
    # phần tiếng Việt, mà im lặng bỏ qua sẽ đẻ ra tên rỗng trên web.
    unknown = sorted({w["matched_charm"]["apiName"] for w in wisps} - set(by_api))
    if unknown:
        raise SystemExit(f"Khong tim thay apiName trong bang charm: {unknown}")

    # bảng charm là nguồn tiếng Việt; chốt lại rằng phía tiếng Anh của file scrape
    # khớp bảng charm, nếu không thì matched_charm đã sai và cả bản vá vô nghĩa.
    mismatched_en = [w["name_en"] for w in wisps if by_api[w["matched_charm"]["apiName"]]["name_en"] != w["name_en"]]
    if mismatched_en:
        raise SystemExit(f"name_en lech so voi charm, matched_charm khong dang tin: {mismatched_en[:5]}")

    built = [build_wisp(w, by_api, extra["desc"], localize_trait) for w in wisps]
    built.sort(key=lambda w: (w["cost"] if w["cost"] is not None else 0, w["nameVi"]))

    TS_OUT.write_text(TS_HEADER + json.dumps(built, ensure_ascii=False) + ";\n", encoding="utf-8")

    fixed = sum(1 for w in wisps if by_api[w["matched_charm"]["apiName"]]["name"] != w["name_vi"])
    with_upgrade = sum(1 for w in built if w["blossomUpgradeDescriptionVi"])
    lost_upgrade = sum(1 for w in wisps if w.get("blossom_upgrade_description_en")) - with_upgrade
    print(f"Wrote {len(built)} wisps -> {TS_OUT.relative_to(WEBSITE)}")
    print(f"  {fixed} ten tieng Viet duoc sua lai tu bang charm (lech hang tu ban scrape)")
    print(f"  {with_upgrade} co mo ta nang cap Hoa Linh" + (f", {lost_upgrade} khong do duoc charm nang cap" if lost_upgrade else ""))


if __name__ == "__main__":
    main()
