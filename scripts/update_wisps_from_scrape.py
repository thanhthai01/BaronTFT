"""Dựng lại Website/src/content/set18/set18-wisps.ts từ Set18/assets/wisps/wisps.json — bản
scrape DOM trực tiếp từ metatft.com/new-set#Wisps (176 linh hỏa, có category/tier/giá,
dữ liệu nâng cấp Hoa Linh, khoảng xuất hiện theo stage-round, điều kiện kích hoạt).

Khác với Set18/data/metatft_set18_vi.json (không có field "wisps"), đây là nguồn duy nhất có
đủ field cho thiết kế linh hỏa: icon phân loại theo category+tier, toggle "nâng cấp Hoa
Linh", khoảng xuất hiện.

## Vá lệch hàng Anh–Việt (2026-08-01)

Bản scrape gốc cào trang ở 2 ngôn ngữ thành 2 danh sách rồi ghép theo INDEX. Hai danh
sách đó được sắp xếp theo bảng chữ cái của chính ngôn ngữ mình, nên lệch nhau: 114/176
linh hỏa mang tên + mô tả tiếng Việt của một linh hỏa khác. Ví dụ `Counterspell`
(apiName `DA_18_Counterspell`) bị gán name_vi "Dư Chấn" — vốn là tên của `Aftershock`.
Đối chiếu với bảng charm trong Set18/data/metatft_set18_vi.json cho thấy:

    name_en / description_en / cost / tier / category  → khớp charm 176/176 (đúng)
    name_vi / description_vi / ...                     → khớp charm  62/176 (lệch)

Nên script KHÔNG còn đọc bất kỳ field `*_vi` nào từ file scrape. Toàn bộ phần tiếng Việt
được lấy lại từ bảng charm, khoá bằng `matched_charm.apiName` — nguồn có sẵn cả `name`
(VI) lẫn `name_en` cho từng apiName, nên ghép luôn đúng cặp:

    name_vi        ← charm[apiName].name
    description_vi ← charm[apiName].desc
    upgrade_vi     ← charm[apiName + "_Upgrade"].desc, dự phòng khớp theo desc_en
    appearsVi      ← dựng từ matched_charm.round_bounds (thay vì chuỗi DOM đã lệch)
    conditionsVi   ← dịch từ conditions_en (đã đúng hàng) qua CONDITION_PATTERNS

File scrape gốc Set18/assets/wisps/wisps.json được giữ nguyên — sửa ở bước dựng, không sửa
dữ liệu thô. Nếu lần sau scrape lại được cả 2 ngôn ngữ theo apiName thì bỏ hẳn phần vá.

## Điều kiện kích hoạt

conditions_en cào về dính liền không có dấu phân cách (vd "Have no 3-star championsBoard
value between 8 and 18First 15 seconds of planning"). CONDITION_SPLIT_RE chèn ranh giới
trước các từ khoá mở đầu quen thuộc (Have/Be/Not/At least/First/Board), CONDITION_PATTERNS
dịch từng khung câu, rồi tên tộc/hệ trong câu được thay bằng tên tiếng Việt lấy từ bảng
traits. Mẫu câu lạ không khớp rule nào thì giữ nguyên tiếng Anh (còn hơn dịch sai).

Chạy từ Website/: python scripts/update_wisps_from_scrape.py
(Set18/ không nằm trong git repo nào nên script sống ở đây, cạnh 3 script cùng loại.)
"""

