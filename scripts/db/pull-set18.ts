function omitKeys<T extends Record<string, unknown>>(obj: T, keys: (keyof T)[]): T {
  const copy = { ...obj };
  for (const k of keys) delete copy[k];
  return copy;
}

/** Xoá field optional (kiểu `foo?: X`, KHÔNG phải `foo: X | null`) khi giá trị
 * là null — gán thẳng null vào field optional sẽ vỡ type (X | undefined, không
 * nhận null). Field nullable thật sự (vd Set18Wisp.cost: number | null) không
 * được liệt vào đây, phải giữ nguyên null. */
function stripNullOptionals<T extends Record<string, unknown>>(obj: T, optionalKeys: (keyof T)[]): T {
  const copy = { ...obj };
  for (const k of optionalKeys) {
    if (copy[k] === null) delete copy[k];
  }
  return copy;
}

function writeGenerated(path: string, header: string[], exportLines: string | string[]) {
  const lines = Array.isArray(exportLines) ? exportLines : [exportLines];
  writeFileSync(path, [...header, '', ...lines, ''].join('\n'));
}

async function pullChampions() {
  const rows = await db
    .select()
    .from(set18Champions)
    .orderBy(asc(set18Champions.cost), asc(set18Champions.name));
  const data = rows.map((r) => stripNullOptionals(omitKeys(r, ['id', 'updatedAt']), ['forms', 'nicknameVi']));
  writeGenerated(
    'src/content/set18/set18-champions.ts',
    ['// GENERATED FILE — do not edit by hand.', '// Generated by Website/scripts/db/pull-set18.ts từ bảng set18_champions trên Neon.', '', "import type { Set18Champion } from './set18-types';"],
    [
      `export const set18Champions: Set18Champion[] = ${JSON.stringify(data)};`,
      'export const set18ChampionByName = new Map(set18Champions.map((champion) => [champion.name, champion]));',
    ],
  );
  console.log(`✓ set18-champions.ts: ${data.length} dòng`);
  return rows;
}

