type EntityIndexEntry = {
  id: string;
  kind: 'champion' | 'trait' | 'augment' | 'wisp';
  name: string;
  nameVi?: string;
  icon: string;
  accent?: string;
  cost?: number;
  rarity?: string;
};

async function pullEntityIndex(
  champions: { id: string; name: string; image: string; cost: number; costColor: string }[],
  traits: { id: string; name: string; vi: string; icon: string; accent: string }[],
  augments: { id: string; name: string; nameVi: string; icon: string; rarityColor: string; rarity: string }[],
  wisps: { id: string; name: string; nameVi: string; categoryIcon: string }[],
) {
  const entries: EntityIndexEntry[] = [
    ...champions.map((c) => ({ id: c.id, kind: 'champion' as const, name: c.name, icon: c.image, cost: c.cost, accent: c.costColor })),
    ...traits.map((t) => ({ id: t.id, kind: 'trait' as const, name: t.name, nameVi: t.vi, icon: t.icon, accent: t.accent })),
    ...augments.map((a) => ({ id: a.id, kind: 'augment' as const, name: a.name, nameVi: a.nameVi, icon: a.icon, accent: a.rarityColor, rarity: a.rarity })),
    ...wisps.map((w) => ({ id: w.id, kind: 'wisp' as const, name: w.name, nameVi: w.nameVi, icon: w.categoryIcon })),
  ];
  writeFileSync(
    'src/content/set18/set18-entity-index.ts',
    [
      '// GENERATED FILE — do not edit by hand.',
      '// Generated by Website/scripts/db/pull-set18.ts từ 4 bảng set18_* trên Neon.',
      '',
      "import type { Set18EntityIndexEntry, Set18EntityKind } from './set18-types';",
      '',
      `export const set18EntityIndex: Set18EntityIndexEntry[] = ${JSON.stringify(entries)};`,
      'export const set18EntityById = new Map(set18EntityIndex.map((entry) => [entry.id, entry]));',
      'export const set18EntityByKindAndName = new Map(set18EntityIndex.map((entry) => [`${entry.kind}:${entry.name}`, entry]));',
      'export function findSet18Entity(kind: Set18EntityKind, name: string) {',
      '  return set18EntityByKindAndName.get(`${kind}:${name}`);',
      '}',
      '',
    ].join('\n'),
  );
  console.log(`✓ set18-entity-index.ts: ${entries.length} dòng`);
  return entries;
}

const ENTRY_OPTIONAL_KEYS = ['entityId', 'note', 'icon', 'cost', 'rarity', 'wispTier', 'wispCategory', 'breakpoint', 'breakpointStyle', 'changes'] as const;
const REPORT_OPTIONAL_KEYS = ['source', 'entitySet', 'summaryOrigin', 'rhythmVi', 'impacts'] as const;

async function pullPatchNotes() {
  // reportOrder tăng dần = cũ dần; 0 luôn là bản mới nhất (patchReports[0]).
  const reports = await db.select().from(patchReportsTable).orderBy(asc(patchReportsTable.reportOrder));
  const entries = await db.select().from(patchEntriesTable).orderBy(asc(patchEntriesTable.sortOrder));

  const data = reports.map((report) => {
    const reportEntries = entries
      .filter((e) => e.reportId === report.id)
      .map((e) => stripNullOptionals(omitKeys(e, ['reportId', 'sortOrder']), [...ENTRY_OPTIONAL_KEYS]));
    const reportFields = stripNullOptionals(omitKeys(report, ['createdAt', 'reportOrder']), [...REPORT_OPTIONAL_KEYS]);
    return { ...reportFields, entries: reportEntries };
  });

  writeFileSync(
    'src/content/patch-notes.generated.ts',
    [
      '// GENERATED FILE — do not edit by hand.',
      '// Generated by Website/scripts/db/pull-set18.ts từ bảng patch_reports/patch_entries trên Neon.',
      "// Sửa bằng cách sửa DB (qua scripts/db/apply-patch-draft.ts) rồi chạy lại 'pnpm db:pull'.",
      '',
      "import type { PatchReport } from './patch-notes';",
      '',
      `export const patchReports: PatchReport[] = ${JSON.stringify(data)};`,
      '',
    ].join('\n'),
  );
  console.log(`✓ patch-notes.generated.ts: ${data.length} bản vá, ${entries.length} mục`);
}

async function main() {
  const [champions, traits, augments, wisps] = await Promise.all([pullChampions(), pullTraits(), pullAugments(), pullWisps()]);
  await pullItems();
  const entityIndexEntries = await pullEntityIndex(champions, traits, augments, wisps);
  writeSet18Slugs(
    buildSet18Slugs(entityIndexEntries),
    'Generated by Website/scripts/db/pull-set18.ts từ set18-entity-index vừa build ở trên.',
  );
  await pullPatchNotes();
  console.log('\nĐã ghi đè file .ts từ DB — chạy `git diff` trong Website/ để duyệt trước khi commit.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
